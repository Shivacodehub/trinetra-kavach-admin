"""PostgreSQL schema. Public identifiers are UUIDs or random strings, never serial ints."""
import uuid
from datetime import datetime
from decimal import Decimal

from sqlalchemy import (JSON, Boolean, CheckConstraint, DateTime, ForeignKey, Index,
                        Integer, Numeric, String, Text, UniqueConstraint, Uuid, func)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base

JSONType = JSON().with_variant(JSONB, "postgresql")


def _pk() -> Mapped[uuid.UUID]:
    return mapped_column(Uuid, primary_key=True, default=uuid.uuid4)


def _now_col(**kw) -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now(), nullable=False, **kw)


class TimestampMixin:
    created_at: Mapped[datetime] = _now_col()
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False)


class Organization(TimestampMixin, Base):
    __tablename__ = "organizations"
    id: Mapped[uuid.UUID] = _pk()
    name: Mapped[str] = mapped_column(String(160), unique=True)
    code: Mapped[str] = mapped_column(String(32), unique=True)
    org_type: Mapped[str] = mapped_column(String(40), default="industrial")
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    workers: Mapped[list["Worker"]] = relationship(back_populates="organization")


class Admin(TimestampMixin, Base):
    __tablename__ = "admins"
    id: Mapped[uuid.UUID] = _pk()
    email: Mapped[str] = mapped_column(String(254), unique=True, index=True)
    full_name: Mapped[str] = mapped_column(String(120))
    password_hash: Mapped[str] = mapped_column(String(255))
    role: Mapped[str] = mapped_column(String(30), default="safety_admin")
    organization_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("organizations.id"))
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    last_login_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class Worker(TimestampMixin, Base):
    __tablename__ = "workers"
    __table_args__ = (
        CheckConstraint("preferred_language IN ('en','hi','sat')", name="ck_worker_language"),
        Index("ix_workers_org", "organization_id"),
    )
    id: Mapped[uuid.UUID] = _pk()
    worker_code: Mapped[str] = mapped_column(String(32), unique=True, index=True)  # e.g. WK-001
    name: Mapped[str] = mapped_column(String(120), index=True)
    email: Mapped[str | None] = mapped_column(String(254))
    phone: Mapped[str | None] = mapped_column(String(20))
    organization_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("organizations.id"))
    department: Mapped[str | None] = mapped_column(String(80))
    role_title: Mapped[str | None] = mapped_column(String(80))
    preferred_language: Mapped[str] = mapped_column(String(5), default="en")
    pin_hash: Mapped[str | None] = mapped_column(String(255))  # for Unity app login (Phase 2)
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    is_demo: Mapped[bool] = mapped_column(Boolean, default=False)
    last_activity_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    organization: Mapped[Organization] = relationship(back_populates="workers")


class Module(TimestampMixin, Base):
    __tablename__ = "modules"
    id: Mapped[uuid.UUID] = _pk()
    code: Mapped[str] = mapped_column(String(32), unique=True)
    name: Mapped[str] = mapped_column(String(160))
    description: Mapped[str] = mapped_column(Text, default="")
    pass_mark: Mapped[int] = mapped_column(Integer, default=70)
    config_label: Mapped[str] = mapped_column(String(80), default="Demo Training Configuration")
    content_version: Mapped[str] = mapped_column(String(20), default="demo-0.1")
    is_active: Mapped[bool] = mapped_column(Boolean, default=True)
    scenarios: Mapped[list["Scenario"]] = relationship(back_populates="module")


class Scenario(TimestampMixin, Base):
    __tablename__ = "scenarios"
    __table_args__ = (UniqueConstraint("module_id", "code", name="uq_scenario_module_code"),)
    id: Mapped[uuid.UUID] = _pk()
    module_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("modules.id"), index=True)
    code: Mapped[str] = mapped_column(String(48))
    name: Mapped[str] = mapped_column(String(160))
    description: Mapped[str] = mapped_column(Text, default="")
    module: Mapped[Module] = relationship(back_populates="scenarios")


class TrainingAttempt(TimestampMixin, Base):
    """One training run. `attempt_id` is generated by the Android app (idempotency key)."""
    __tablename__ = "training_attempts"
    __table_args__ = (
        CheckConstraint("status IN ('in_progress','completed','abandoned')", name="ck_attempt_status"),
        Index("ix_attempts_worker_started", "worker_id", "started_at"),
        Index("ix_attempts_module", "module_id"),
    )
    id: Mapped[uuid.UUID] = _pk()
    attempt_id: Mapped[str] = mapped_column(String(64), unique=True, index=True)
    worker_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("workers.id"))
    module_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("modules.id"))
    scenario_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("scenarios.id"))
    status: Mapped[str] = mapped_column(String(20), default="completed")
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    ended_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    duration_seconds: Mapped[int | None] = mapped_column(Integer)
    language: Mapped[str | None] = mapped_column(String(5))
    device_id: Mapped[str | None] = mapped_column(String(64))
    app_version: Mapped[str | None] = mapped_column(String(20))
    client_created_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    synced_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), index=True)
    is_demo: Mapped[bool] = mapped_column(Boolean, default=False)
    worker: Mapped[Worker] = relationship()
    module: Mapped[Module] = relationship()
    scenario: Mapped[Scenario] = relationship()
    events: Mapped[list["AssessmentEvent"]] = relationship(
        back_populates="attempt", order_by="AssessmentEvent.sequence", cascade="all, delete-orphan")
    score: Mapped["AssessmentScore | None"] = relationship(back_populates="attempt", uselist=False)


class AssessmentEvent(Base):
    """Individual worker action evaluated by the on-device assessment engine."""
    __tablename__ = "assessment_events"
    __table_args__ = (
        UniqueConstraint("attempt_pk", "sequence", name="uq_event_attempt_seq"),
        CheckConstraint("risk_level IN ('low','medium','high','critical')", name="ck_event_risk"),
    )
    id: Mapped[uuid.UUID] = _pk()
    attempt_pk: Mapped[uuid.UUID] = mapped_column(ForeignKey("training_attempts.id", ondelete="CASCADE"), index=True)
    sequence: Mapped[int] = mapped_column(Integer)
    event_type: Mapped[str] = mapped_column(String(64))
    category: Mapped[str | None] = mapped_column(String(40))  # behavioural dimension
    occurred_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    action_taken: Mapped[str] = mapped_column(String(200))
    expected_action: Mapped[str] = mapped_column(String(200))
    is_correct: Mapped[bool] = mapped_column(Boolean)
    score_impact: Mapped[Decimal] = mapped_column(Numeric(6, 2))
    points_possible: Mapped[Decimal] = mapped_column(Numeric(6, 2), default=0)
    risk_level: Mapped[str] = mapped_column(String(10), default="low")
    scenario_state: Mapped[dict | None] = mapped_column(JSONType)
    is_demo: Mapped[bool] = mapped_column(Boolean, default=False)
    attempt: Mapped[TrainingAttempt] = relationship(back_populates="events")


class AssessmentScore(Base):
    __tablename__ = "assessment_scores"
    id: Mapped[uuid.UUID] = _pk()
    attempt_pk: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("training_attempts.id", ondelete="CASCADE"), unique=True)
    score: Mapped[Decimal] = mapped_column(Numeric(5, 2))
    passed: Mapped[bool] = mapped_column(Boolean, index=True)
    pass_mark_used: Mapped[int] = mapped_column(Integer)
    score_source: Mapped[str] = mapped_column(String(30), default="derived_from_events")
    client_reported_score: Mapped[Decimal | None] = mapped_column(Numeric(5, 2))
    behavior_metrics: Mapped[dict | None] = mapped_column(JSONType)
    computed_at: Mapped[datetime] = _now_col()
    attempt: Mapped[TrainingAttempt] = relationship(back_populates="score")


class Certificate(TimestampMixin, Base):
    __tablename__ = "certificates"
    __table_args__ = (
        CheckConstraint("status IN ('valid','revoked')", name="ck_cert_status"),
        Index("ix_certs_worker", "worker_id"),
    )
    id: Mapped[uuid.UUID] = _pk()
    certificate_id: Mapped[str] = mapped_column(String(40), unique=True, index=True)  # public, random
    attempt_pk: Mapped[uuid.UUID] = mapped_column(ForeignKey("training_attempts.id"), unique=True)
    worker_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("workers.id"))
    module_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("modules.id"))
    score: Mapped[Decimal] = mapped_column(Numeric(5, 2))
    issued_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    expires_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    status: Mapped[str] = mapped_column(String(10), default="valid")
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    revoked_reason: Mapped[str | None] = mapped_column(String(300))
    revoked_by: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("admins.id"))
    is_demo: Mapped[bool] = mapped_column(Boolean, default=False)
    worker: Mapped[Worker] = relationship()
    module: Mapped[Module] = relationship()


class CertificateVerification(Base):
    """Log of every public verification lookup (found or not)."""
    __tablename__ = "certificate_verifications"
    id: Mapped[uuid.UUID] = _pk()
    certificate_pk: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("certificates.id"), index=True)
    certificate_id_queried: Mapped[str] = mapped_column(String(64))
    result: Mapped[str] = mapped_column(String(10))  # valid | revoked | invalid
    verified_at: Mapped[datetime] = _now_col()
    requester_hash: Mapped[str | None] = mapped_column(String(64))  # hashed IP, never raw


class SyncLog(Base):
    __tablename__ = "sync_logs"
    __table_args__ = (CheckConstraint("status IN ('accepted','duplicate','rejected')", name="ck_sync_status"),)
    id: Mapped[uuid.UUID] = _pk()
    device_id: Mapped[str | None] = mapped_column(String(64))
    worker_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("workers.id"))
    attempt_id: Mapped[str] = mapped_column(String(64), index=True)
    status: Mapped[str] = mapped_column(String(10))
    detail: Mapped[str | None] = mapped_column(String(300))
    received_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), index=True)


class AuditLog(Base):
    __tablename__ = "audit_logs"
    id: Mapped[uuid.UUID] = _pk()
    admin_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("admins.id"), index=True)
    action: Mapped[str] = mapped_column(String(60), index=True)
    entity_type: Mapped[str] = mapped_column(String(40))
    entity_id: Mapped[str | None] = mapped_column(String(64))
    timestamp: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now(), index=True)
    meta: Mapped[dict | None] = mapped_column("metadata", JSONType)


class RevokedToken(Base):
    """Server-side logout: a signed-out token's id is kept here until the token would have expired anyway."""
    __tablename__ = "revoked_tokens"
    jti: Mapped[str] = mapped_column(String(64), primary_key=True)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), index=True)
    revoked_at: Mapped[datetime] = _now_col()
